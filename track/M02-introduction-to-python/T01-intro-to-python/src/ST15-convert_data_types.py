# Initially Assigned values to variables
Age = "22" #str
print(type(Age))
Course_fee = "10000.00" #str
print(type(Course_fee))
Attempts = 3 #int
print(type(Attempts))

# Convert to other data types
age = int(Age)
course_fee = float(Course_fee)
attempts = str(Attempts)

# Display the converted values and their converted data types
print(age)
print(type(age))
print(course_fee)
print(type(course_fee))
print(attempts)
print(type(attempts))
